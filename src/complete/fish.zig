//! The fish script: a walk of the line that names the command it is in, and
//! a `complete` line for each option, subcommand and positional, under the
//! condition that the line is in that command.
const std = @import("std");
const tree = @import("tree.zig");
const bash = @import("bash.zig");
const Writer = std.Io.Writer;
const Node = tree.Node;

pub fn write(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try w.print("# fish completion for {s}, generated by ensign.\n", .{name});
    try kinds(nodes, w, name);
    try bash.writeAll(w,
        \\function __ensign_<id>_state
        \\    set -l path ''
        \\    set -l pending ''
        \\    set -l done 0
        \\    set -l count 0
        \\    set -l tokens (commandline -opc)
        \\    set -e tokens[1]
        \\    for word in $tokens
        \\        if test -n "$pending"
        \\            set pending ''
        \\            continue
        \\        end
        \\        if test $done = 1
        \\            set count (math $count + 1)
        \\            continue
        \\        end
        \\        switch $word
        \\            case --
        \\                set done 1
        \\            case '--*=*'
        \\            case -
        \\                set count (math $count + 1)
        \\            case '--*'
        \\                set -l kind (__ensign_<id>_kind "$path:$word")
        \\                if test -n "$kind" -a "$kind" != flag
        \\                    set pending $word
        \\                end
        \\            case '-*'
        \\                set -l n (string length -- $word)
        \\                for k in (seq 2 $n)
        \\                    set -l kind (__ensign_<id>_kind "$path:-"(string sub -s $k -l 1 -- $word))
        \\                    if test -n "$kind" -a "$kind" != flag
        \\                        if test $k = $n
        \\                            set pending "-"(string sub -s $k -l 1 -- $word)
        \\                        end
        \\                        break
        \\                    end
        \\                end
        \\            case '*'
        \\                set -l next (__ensign_<id>_sub "$path:$word")
        \\                if test $status = 0
        \\                    set path $next
        \\                    set count 0
        \\                else
        \\                    set count (math $count + 1)
        \\                end
        \\        end
        \\    end
        \\    echo $count
        \\    if test -n "$pending"; echo $pending; else; echo none; end
        \\    echo $path
        \\end
        \\function __ensign_<id>_at
        \\    set -l state (__ensign_<id>_state)
        \\    test "$state[2]" = none -a "$state[3]" = "$argv[1]"
        \\end
        \\function __ensign_<id>_positional
        \\    set -l state (__ensign_<id>_state)
        \\    test "$state[2]" = none -a "$state[3]" = "$argv[1]"; or return 1
        \\    if test "$argv[3]" = list
        \\        test $state[1] -ge $argv[2]
        \\    else
        \\        test $state[1] -eq $argv[2]
        \\    end
        \\end
        \\function __ensign_<id>_pending
        \\    set -l state (__ensign_<id>_state)
        \\    test "$state[2]" != none; or return 1
        \\    test (__ensign_<id>_kind "$state[3]:$state[2]") = "$argv[1]"
        \\end
        \\function __ensign_<id>_pending_values
        \\    set -l state (__ensign_<id>_state)
        \\    __ensign_<id>_values "$state[3]:$state[2]"
        \\end
        \\function __ensign_<id>_ask
        \\    set -l tokens (commandline -opc)
        \\    set -l cur (commandline -ct)
        \\    if string match -q -- '--*=*' $cur
        \\        set cur (string replace -r '^[^=]*=' '' -- $cur)
        \\    end
        \\    env ENSIGN_COMPLETE="1:$argv[1]" $tokens $cur 2>/dev/null
        \\end
        \\function __ensign_<id>_pending_ask
        \\    set -l state (__ensign_<id>_state)
        \\    __ensign_<id>_ask "$state[3]:$state[2]"
        \\end
        \\
    , name);
    for (nodes) |node| try lines(node, w, name);
    // The value of an option the line ends on, whichever spelling it was given.
    const pending = [_][2][]const u8{
        .{ "values", "-f -a '(__ensign_<id>_pending_values)'" },
        .{ "file", "-F" },
        .{ "directory", "-f -a '(__fish_complete_directories)'" },
        .{ "command", "-f -a '(__fish_complete_command)'" },
        .{ "program", "-f -a '(__ensign_<id>_pending_ask)'" },
        .{ "text", "-f" },
    };
    inline for (pending) |p| {
        try w.print("complete -c {s} -n '", .{name});
        try bash.writeAll(w, "__ensign_<id>_pending " ++ p[0] ++ "' " ++ p[1] ++ "\n", name);
    }
}

/// `__ensign_<name>_kind` and `__ensign_<name>_sub`, as `switch`es.
fn kinds(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try bash.writeAll(w, "function __ensign_<id>_kind\n    switch $argv[1]\n", name);
    for (nodes) |node| for (node.entries) |e| {
        try w.writeAll("        case");
        for (e.spellings) |spelling| try w.print(" '{s}:{s}'", .{ node.path, spelling });
        try w.print("\n            echo {s}\n", .{tree.kindName(e.kind)});
    };
    try w.writeAll("    end\nend\n");
    try bash.writeAll(w, "function __ensign_<id>_values\n    switch $argv[1]\n", name);
    for (nodes) |node| for (node.entries) |e| if (e.kind == .values) {
        try w.writeAll("        case");
        for (e.spellings) |spelling| try w.print(" '{s}:{s}'", .{ node.path, spelling });
        try w.writeAll("\n            printf '%s\\n'");
        for (e.values) |v| try w.print(" {s}", .{v});
        try w.writeByte('\n');
    };
    try w.writeAll("    end\nend\n");
    try bash.writeAll(w, "function __ensign_<id>_sub\n    switch $argv[1]\n", name);
    for (nodes) |node| for (node.subs) |sub| {
        try w.print("        case '{s}:{s}'", .{ node.path, sub.name });
        for (sub.aliases) |alias| try w.print(" '{s}:{s}'", .{ node.path, alias });
        try w.print("\n            echo '{s}'\n", .{sub.path});
    };
    try w.writeAll("        case '*'\n            return 1\n    end\nend\n");
}

fn lines(node: Node, w: *Writer, name: []const u8) Writer.Error!void {
    for (node.entries) |e| {
        if (e.offered.len == 0) continue;
        try start(w, name, node.path);
        for (e.offered) |spelling| {
            if (std.mem.startsWith(u8, spelling, "--")) try w.print(" -l {s}", .{spelling[2..]}) else try w.print(" -s {s}", .{spelling[1..]});
        }
        try argument(w, e.kind, e.values, name, node.path, e.spellings[0]);
        try description(w, e.help);
        try w.writeByte('\n');
    }
    for (node.subs) |sub| if (!sub.hidden) {
        try start(w, name, node.path);
        try w.print(" -f -a {s}", .{sub.name});
        try description(w, sub.help);
        try w.writeByte('\n');
    };
    if (node.subs.len == 0 and node.positionals.len == 0) {
        // Nothing follows: no files either.
        try start(w, name, node.path);
        try w.writeAll(" -f\n");
    }
    for (node.positionals, 0..) |p, n| {
        try w.writeAll("complete -c ");
        try w.writeAll(name);
        try w.print(" -n '__ensign_", .{});
        try tree.writeIdentifier(w, name);
        try w.print("_positional \"{s}\" {d} {s}'", .{ node.path, n, if (p.list) "list" else "one" });
        var key: [24]u8 = undefined;
        switch (p.kind) {
            .file => try w.writeAll(" -F"),
            else => try argument(w, p.kind, p.values, name, node.path, std.mem.print(&key, "#{d}", .{n}) catch unreachable), // unreachable: a usize in decimal fits 24 bytes
        }
        try w.writeByte('\n');
    }
}

fn start(w: *Writer, name: []const u8, path: []const u8) Writer.Error!void {
    try w.print("complete -c {s} -n '__ensign_", .{name});
    try tree.writeIdentifier(w, name);
    try w.print("_at \"{s}\"'", .{path});
}

/// What a value takes: `-x` requires one and offers no files, `-r -F`
/// requires one and offers files.
fn argument(w: *Writer, kind: tree.Kind, values: []const []const u8, name: []const u8, path: []const u8, spelling: []const u8) Writer.Error!void {
    switch (kind) {
        .program => {
            try w.writeAll(" -x -a '(__ensign_");
            try tree.writeIdentifier(w, name);
            try w.print("_ask \"{s}:{s}\")'", .{ path, spelling });
        },
        .flag => {},
        .text => try w.writeAll(" -x"),
        .file => try w.writeAll(" -r -F"),
        .directory => try w.writeAll(" -x -a '(__fish_complete_directories)'"),
        .command => try w.writeAll(" -x -a '(__fish_complete_command)'"),
        .values => {
            try w.writeAll(" -x -a '");
            for (values, 0..) |v, n| try w.print("{s}{s}", .{ if (n == 0) "" else " ", v });
            try w.writeByte('\'');
        },
    }
}

fn description(w: *Writer, help: []const u8) Writer.Error!void {
    if (help.len == 0) return;
    try w.writeAll(" -d '");
    for (help) |c| switch (c) {
        '\\' => try w.writeAll("\\\\"),
        '\'' => try w.writeAll("\\'"),
        else => try w.writeByte(c),
    };
    try w.writeByte('\'');
}

//! The zsh script: the same lookups as bash's, whose `case` zsh reads
//! alike, and offers with their descriptions through `_describe`.
const std = @import("std");
const tree = @import("tree.zig");
const bash = @import("bash.zig");
const Writer = std.Io.Writer;
const Node = tree.Node;

pub fn write(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try w.print("#compdef {s}\n# zsh completion for {s}, generated by ensign.\n", .{ name, name });
    try bash.lookups(nodes, w, name);
    try described(nodes, w, name);
    try bash.writeAll(w,
        \\_ensign_<id>_complete() {
        \\    _ensign_<id>_kind "$1"
        \\    case "$REPLY" in
        \\        values) _ensign_<id>_values "$1"; compadd -- ${=REPLY} ;;
        \\        file) _files ;;
        \\        directory) _files -/ ;;
        \\        command) _command_names -e ;;
        \\        program) _ensign_<id>_ask "$1" ;;
        \\    esac
        \\}
        \\# Asks the program: the words before the one completed, unquoted.
        \\_ensign_<id>_ask() {
        \\    local line v d
        \\    local -a ensign_values
        \\    for line in "${(@f)$(ENSIGN_COMPLETE="1:$1" ${(Q)words[1]} "${(@Q)words[2,CURRENT-1]}" "$value" 2>/dev/null)}"; do
        \\        [[ -z $line ]] && continue
        \\        v="${line%%$'\t'*}"
        \\        d=
        \\        [[ $line == *$'\t'* ]] && d="${line#*$'\t'}"
        \\        ensign_values+=("${v//:/\\:}${d:+:$d}")
        \\    done
        \\    _describe -t values value ensign_values
        \\}
        \\_ensign_<id>() {
        \\    emulate -L zsh
        \\    local cur="${words[CURRENT]}" value="${words[CURRENT]}" word ensign_path= pending= opt= REPLY
        \\    local -a ensign_items
        \\    integer done=0 count=0 i=2 k
        \\    if [[ $cur == --*=* ]]; then
        \\        opt="${cur%%=*}"
        \\        value="${cur#*=}"
        \\        compset -P '*='
        \\    fi
        \\    while (( i < CURRENT )); do
        \\        word="${words[i]}"
        \\        (( i++ ))
        \\        if [[ -n $pending ]]; then pending=; continue; fi
        \\        if (( done )); then (( count++ )); continue; fi
        \\        case "$word" in
        \\            --) done=1 ;;
        \\            --*=*) ;;
        \\            -) (( count++ )) ;;
        \\            --*)
        \\                _ensign_<id>_kind "${ensign_path}:$word"
        \\                if [[ -n $REPLY && $REPLY != flag ]]; then pending="$word"; fi ;;
        \\            -*)
        \\                k=2
        \\                while (( k <= ${#word} )); do
        \\                    _ensign_<id>_kind "${ensign_path}:-${word[k]}"
        \\                    if [[ -n $REPLY && $REPLY != flag ]]; then
        \\                        if (( k == ${#word} )); then pending="-${word[k]}"; fi
        \\                        break
        \\                    fi
        \\                    (( k++ ))
        \\                done ;;
        \\            *)
        \\                if _ensign_<id>_sub "${ensign_path}:$word"; then ensign_path="$REPLY"; count=0; else (( count++ )); fi ;;
        \\        esac
        \\    done
        \\    if [[ -n $pending ]]; then opt="$pending"; fi
        \\    if [[ -n $opt ]]; then _ensign_<id>_complete "${ensign_path}:$opt"; return; fi
        \\    if (( ! done )) && [[ $cur == -* ]]; then
        \\        _ensign_<id>_described "options:${ensign_path}"
        \\        _describe -t options option ensign_items
        \\        return
        \\    fi
        \\    _ensign_<id>_described "commands:${ensign_path}"
        \\    if (( ! done && ${#ensign_items} )); then
        \\        _describe -t commands command ensign_items
        \\        return
        \\    fi
        \\    _ensign_<id>_complete "${ensign_path}:#$count"
        \\}
        \\if [[ $zsh_eval_context[-1] == loadautofunc ]]; then
        \\    _ensign_<id> "$@"
        \\else
        \\    compdef _ensign_<id>
    , name);
    try w.print("{s}\nfi\n", .{name});
}

/// `_ensign_<name>_described`: fills `ensign_items` with `spelling:help`.
fn described(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try bash.writeAll(w, "_ensign_<id>_described() {\n    case \"$1\" in\n", name);
    for (nodes) |node| {
        try w.print("        'options:{s}') ensign_items=(", .{node.path});
        for (node.entries) |e| for (e.offered) |spelling| try item(w, spelling, e.help);
        try w.writeAll(") ;;\n");
        if (node.subs.len == 0) continue;
        try w.print("        'commands:{s}') ensign_items=(", .{node.path});
        for (node.subs) |sub| if (!sub.hidden) try item(w, sub.name, sub.help);
        try w.writeAll(") ;;\n");
    }
    try w.writeAll("        *) ensign_items=() ;;\n    esac\n}\n");
}

/// One `_describe` item in single quotes: `spelling:help`.
fn item(w: *Writer, spelling: []const u8, help: []const u8) Writer.Error!void {
    try w.print(" '{s}", .{spelling});
    if (help.len != 0) {
        try w.writeByte(':');
        for (help) |c| {
            if (c == '\'') try w.writeAll("'\\''") else try w.writeByte(c);
        }
    }
    try w.writeByte('\'');
}

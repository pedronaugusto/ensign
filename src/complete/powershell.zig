//! The PowerShell script: a native argument completer whose lookups are
//! case-sensitive `switch`es, since the command line is.
const std = @import("std");
const tree = @import("tree.zig");
const Writer = std.Io.Writer;
const Node = tree.Node;

pub fn write(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try w.print("# PowerShell completion for {s}, generated by ensign.\n", .{name});
    try w.print("Register-ArgumentCompleter -Native -CommandName '{s}' -ScriptBlock {{\n", .{name});
    try w.writeAll("    param($wordToComplete, $commandAst, $cursorPosition)\n");
    try lookups(nodes, w);
    try w.writeAll(
        \\    $words = @($commandAst.CommandElements | Where-Object { $_.Extent.EndOffset -lt $cursorPosition } | ForEach-Object { $_.Extent.Text })
        \\    $path = ''
        \\    $pending = ''
        \\    $done = $false
        \\    $count = 0
        \\    for ($i = 1; $i -lt $words.Count; $i++) {
        \\        $word = $words[$i]
        \\        if ($pending) { $pending = ''; continue }
        \\        if ($done) { $count++; continue }
        \\        if ($word -ceq '--') { $done = $true }
        \\        elseif ($word -clike '--*=*') { }
        \\        elseif ($word -ceq '-') { $count++ }
        \\        elseif ($word.StartsWith('--')) {
        \\            $kind = Get-EnsignKind "${path}:$word"
        \\            if ($kind -and $kind -cne 'flag') { $pending = $word }
        \\        }
        \\        elseif ($word.StartsWith('-')) {
        \\            for ($k = 1; $k -lt $word.Length; $k++) {
        \\                $kind = Get-EnsignKind ("${path}:-" + $word[$k])
        \\                if ($kind -and $kind -cne 'flag') {
        \\                    if ($k -eq $word.Length - 1) { $pending = $word }
        \\                    break
        \\                }
        \\            }
        \\        }
        \\        else {
        \\            $next = Get-EnsignSub "${path}:$word"
        \\            if ($null -ne $next) { $path = $next; $count = 0 } else { $count++ }
        \\        }
        \\    }
        \\    $cur = [string]$wordToComplete
        \\    $prefix = ''
        \\    $key = ''
        \\    if ($pending) {
        \\        $last = $words[$words.Count - 1]
        \\        $key = if ($last.StartsWith('--')) { "${path}:$last" } else { "${path}:-" + $last[$last.Length - 1] }
        \\    }
        \\    elseif (-not $done -and $cur -clike '--*=*') {
        \\        $prefix = $cur.Substring(0, $cur.IndexOf('=') + 1)
        \\        $key = "${path}:" + $cur.Substring(0, $cur.IndexOf('='))
        \\        $cur = $cur.Substring($prefix.Length)
        \\    }
        \\    $results = [System.Collections.Generic.List[System.Management.Automation.CompletionResult]]::new()
        \\    function Add-EnsignResult([string]$text, [string]$type, [string]$tip) {
        \\        if ($text.StartsWith($cur, [System.StringComparison]::Ordinal)) {
        \\            if (-not $tip) { $tip = $text }
        \\            $results.Add([System.Management.Automation.CompletionResult]::new($prefix + $text, $text, $type, $tip))
        \\        }
        \\    }
        \\    function Add-EnsignValues([string]$valueKey) {
        \\        switch -CaseSensitive (Get-EnsignKind $valueKey) {
        \\            'values' { foreach ($v in @(Get-EnsignValues $valueKey)) { Add-EnsignResult $v 'ParameterValue' '' } }
        \\            'command' { foreach ($c in @(Get-Command -CommandType Application -ErrorAction SilentlyContinue)) { Add-EnsignResult $c.Name 'Command' '' } }
        \\            { $_ -ceq 'file' -or $_ -ceq 'directory' } {
        \\                $cut = $cur.LastIndexOfAny([char[]]@('/', '\'))
        \\                $dir = if ($cut -ge 0) { $cur.Substring(0, $cut + 1) } else { '' }
        \\                $base = if ($dir) { $dir } else { '.' }
        \\                foreach ($item in @(Get-ChildItem -LiteralPath $base -Force -ErrorAction SilentlyContinue)) {
        \\                    if ($_ -ceq 'directory' -and -not $item.PSIsContainer) { continue }
        \\                    $type = if ($item.PSIsContainer) { 'ProviderContainer' } else { 'ProviderItem' }
        \\                    Add-EnsignResult ($dir + $item.Name) $type ''
        \\                }
        \\            }
        \\        }
        \\    }
        \\    if ($key) { Add-EnsignValues $key }
        \\    elseif (-not $done -and $cur.StartsWith('-')) {
        \\        $offer = @(Get-EnsignOffer "options:$path")
        \\        for ($n = 0; $n + 1 -lt $offer.Count; $n += 2) { Add-EnsignResult $offer[$n] 'ParameterName' $offer[$n + 1] }
        \\    }
        \\    else {
        \\        $offer = @(Get-EnsignOffer "commands:$path")
        \\        if (-not $done -and $offer.Count -gt 0) {
        \\            for ($n = 0; $n + 1 -lt $offer.Count; $n += 2) { Add-EnsignResult $offer[$n] 'Command' $offer[$n + 1] }
        \\        }
        \\        else { Add-EnsignValues "${path}:#$count" }
        \\    }
        \\    $results
        \\}
        \\
    );
}

fn lookups(nodes: []const Node, w: *Writer) Writer.Error!void {
    try w.writeAll("    function Get-EnsignKind([string]$key) {\n        switch -CaseSensitive -Exact ($key) {\n");
    for (nodes) |node| {
        for (node.entries) |e| for (e.spellings) |spelling| {
            try w.print("            '{s}:{s}' {{ return '{s}' }}\n", .{ node.path, spelling, tree.kindName(e.kind) });
        };
        for (node.positionals, 0..) |p, n| {
            if (p.list) continue;
            try w.print("            '{s}:#{d}' {{ return '{s}' }}\n", .{ node.path, n, tree.kindName(p.kind) });
        }
    }
    try w.writeAll("            default {}\n        }\n");
    try listPositionals(nodes, w, false);
    try w.writeAll("        return ''\n    }\n");

    try w.writeAll("    function Get-EnsignValues([string]$key) {\n        switch -CaseSensitive -Exact ($key) {\n");
    for (nodes) |node| {
        for (node.entries) |e| if (e.kind == .values) for (e.spellings) |spelling| {
            try w.print("            '{s}:{s}'", .{ node.path, spelling });
            try values(w, e.values);
        };
        for (node.positionals, 0..) |p, n| if (p.kind == .values and !p.list) {
            try w.print("            '{s}:#{d}'", .{ node.path, n });
            try values(w, p.values);
        };
    }
    try w.writeAll("            default {}\n        }\n");
    try listPositionals(nodes, w, true);
    try w.writeAll("        return @()\n    }\n");

    try w.writeAll("    function Get-EnsignSub([string]$key) {\n        switch -CaseSensitive -Exact ($key) {\n");
    for (nodes) |node| for (node.subs) |sub| {
        try w.print("            '{s}:{s}'", .{ node.path, sub.name });
        for (sub.aliases) |alias| try w.print(" {{ return '{s}' }}\n            '{s}:{s}'", .{ sub.path, node.path, alias });
        try w.print(" {{ return '{s}' }}\n", .{sub.path});
    };
    try w.writeAll("            default {}\n        }\n        return $null\n    }\n");

    try w.writeAll("    function Get-EnsignOffer([string]$key) {\n        switch -CaseSensitive -Exact ($key) {\n");
    for (nodes) |node| {
        try w.print("            'options:{s}' {{ return @(", .{node.path});
        var first = true;
        for (node.entries) |e| for (e.offered) |spelling| {
            try pair(w, spelling, e.help, first);
            first = false;
        };
        try w.writeAll(") }\n");
        try w.print("            'commands:{s}' {{ return @(", .{node.path});
        first = true;
        for (node.subs) |sub| if (!sub.hidden) {
            try pair(w, sub.name, sub.help, first);
            first = false;
        };
        try w.writeAll(") }\n");
    }
    try w.writeAll("            default {}\n        }\n        return @()\n    }\n");
}

/// A list positional takes every index from its own on: a wildcard match.
fn listPositionals(nodes: []const Node, w: *Writer, only_values: bool) Writer.Error!void {
    var any = false;
    for (nodes) |node| for (node.positionals) |p| {
        if (!p.list or (only_values and p.kind != .values)) continue;
        if (!any) try w.writeAll("        switch -CaseSensitive -Wildcard ($key) {\n");
        any = true;
        try w.print("            '{s}:#*'", .{node.path});
        if (only_values) try values(w, p.values) else try w.print(" {{ return '{s}' }}\n", .{tree.kindName(p.kind)});
    };
    if (any) try w.writeAll("            default {}\n        }\n");
}

fn values(w: *Writer, list: []const []const u8) Writer.Error!void {
    try w.writeAll(" { return @(");
    for (list, 0..) |v, n| try w.print("{s}'{s}'", .{ if (n == 0) "" else ", ", v });
    try w.writeAll(") }\n");
}

fn pair(w: *Writer, text: []const u8, help: []const u8, first: bool) Writer.Error!void {
    if (!first) try w.writeAll(", ");
    try w.print("'{s}', ", .{text});
    try quoted(w, help);
}

fn quoted(w: *Writer, s: []const u8) Writer.Error!void {
    try w.writeByte('\'');
    for (s) |c| {
        if (c == '\'') try w.writeAll("''") else try w.writeByte(c);
    }
    try w.writeByte('\'');
}

//! The bash script: functions keyed by `path:spelling`, and a walk of the
//! words before the cursor. It runs on bash 3.2 and later.
const std = @import("std");
const tree = @import("tree.zig");
const Writer = std.Io.Writer;
const Node = tree.Node;

pub fn write(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try w.print("# bash completion for {s}, generated by ensign.\n", .{name});
    try lookups(nodes, w, name);
    try offers(nodes, w, name);
    try writeAll(w,
        \\_ensign_<id>_complete() {
        \\    local IFS='
        \\'
        \\    _ensign_<id>_kind "$1"
        \\    case "$REPLY" in
        \\        values)
        \\            _ensign_<id>_values "$1"
        \\            IFS=$' \n'
        \\            COMPREPLY=($(compgen -P "$3" -W "$REPLY" -- "$2")) ;;
        \\        file)
        \\            COMPREPLY=($(compgen -P "$3" -f -- "$2"))
        \\            [ -z "$3" ] && type compopt >/dev/null 2>&1 && compopt -o filenames ;;
        \\        directory)
        \\            COMPREPLY=($(compgen -P "$3" -d -- "$2"))
        \\            [ -z "$3" ] && type compopt >/dev/null 2>&1 && compopt -o filenames ;;
        \\        command) COMPREPLY=($(compgen -P "$3" -c -- "$2")) ;;
        \\        *) COMPREPLY=() ;;
        \\    esac
        \\    return 0
        \\}
        \\_ensign_<id>() {
        \\    local cur="${COMP_WORDS[COMP_CWORD]}" end=$COMP_CWORD opt= prefix= word path= pending= done=0 count=0 i=1 k REPLY
        \\    # bash splits `--name=value` at `=` when it is a word break.
        \\    if [ "$cur" = "=" ] && [ $end -gt 1 ]; then
        \\        end=$((end - 1)); opt="${COMP_WORDS[end]}"; cur=
        \\    elif [ $end -gt 2 ] && [ "${COMP_WORDS[end - 1]}" = "=" ]; then
        \\        end=$((end - 2)); opt="${COMP_WORDS[end]}"
        \\    elif [[ "$cur" == --*=* ]]; then
        \\        opt="${cur%%=*}"; prefix="$opt="; cur="${cur#*=}"
        \\    fi
        \\    while [ $i -lt $end ]; do
        \\        word="${COMP_WORDS[i]}"
        \\        i=$((i + 1))
        \\        if [ -n "$pending" ]; then pending=; continue; fi
        \\        if [ $done = 1 ]; then count=$((count + 1)); continue; fi
        \\        case "$word" in
        \\            --) done=1 ;;
        \\            --*=*) ;;
        \\            -) count=$((count + 1)) ;;
        \\            --*)
        \\                if [ "${COMP_WORDS[i]}" = "=" ]; then
        \\                    i=$((i + 2))
        \\                else
        \\                    _ensign_<id>_kind "$path:$word"
        \\                    if [ -n "$REPLY" ] && [ "$REPLY" != flag ]; then pending="$word"; fi
        \\                fi ;;
        \\            -*)
        \\                k=1
        \\                while [ $k -lt ${#word} ]; do
        \\                    _ensign_<id>_kind "$path:-${word:k:1}"
        \\                    k=$((k + 1))
        \\                    if [ -n "$REPLY" ] && [ "$REPLY" != flag ]; then
        \\                        if [ $k -eq ${#word} ]; then pending="-${word:k-1:1}"; fi
        \\                        break
        \\                    fi
        \\                done
        \\                # `-o=value`, split at `=` like a long option.
        \\                if [ -n "$pending" ] && [ "${COMP_WORDS[i]}" = "=" ]; then pending=; i=$((i + 2)); fi ;;
        \\            *)
        \\                if _ensign_<id>_sub "$path:$word"; then path="$REPLY"; count=0; else count=$((count + 1)); fi ;;
        \\        esac
        \\    done
        \\    if [ -n "$pending" ]; then opt="$pending"; fi
        \\    if [ -n "$opt" ]; then _ensign_<id>_complete "$path:$opt" "$cur" "$prefix"; return 0; fi
        \\    if [ $done = 0 ] && [[ "$cur" == -* ]]; then
        \\        _ensign_<id>_offer "options:$path"
        \\        local IFS=$' \n'
        \\        COMPREPLY=($(compgen -W "$REPLY" -- "$cur"))
        \\        return 0
        \\    fi
        \\    _ensign_<id>_offer "commands:$path"
        \\    if [ $done = 0 ] && [ -n "$REPLY" ]; then
        \\        local IFS=$' \n'
        \\        COMPREPLY=($(compgen -W "$REPLY" -- "$cur"))
        \\        return 0
        \\    fi
        \\    _ensign_<id>_complete "$path:#$count" "$cur" ""
        \\}
        \\
    , name);
    try w.print("complete -F _ensign_", .{});
    try tree.writeIdentifier(w, name);
    try w.print(" {s}\n", .{name});
}

/// Writes `template` with each `<id>` replaced by the program's identifier.
pub fn writeAll(w: *Writer, comptime template: []const u8, name: []const u8) Writer.Error!void {
    var parts = std.mem.splitSequence(u8, template, "<id>");
    try w.writeAll(parts.first());
    while (parts.next()) |part| {
        try tree.writeIdentifier(w, name);
        try w.writeAll(part);
    }
}

pub fn lookups(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try writeAll(w, "_ensign_<id>_kind() {\n    case \"$1\" in\n", name);
    for (nodes) |node| {
        for (node.entries) |e| {
            try pattern(w, node.path, e.spellings);
            try w.print(") REPLY={s} ;;\n", .{tree.kindName(e.kind)});
        }
        try positionals(w, node, false);
    }
    try w.writeAll("        *) REPLY= ;;\n    esac\n}\n");

    try writeAll(w, "_ensign_<id>_values() {\n    case \"$1\" in\n", name);
    for (nodes) |node| {
        for (node.entries) |e| if (e.kind == .values) {
            try pattern(w, node.path, e.spellings);
            try words(w, ") REPLY='", e.values);
            try w.writeAll("' ;;\n");
        };
        try positionals(w, node, true);
    }
    try w.writeAll("        *) REPLY= ;;\n    esac\n}\n");

    try writeAll(w, "_ensign_<id>_sub() {\n    case \"$1\" in\n", name);
    for (nodes) |node| for (node.subs) |sub| {
        try w.print("        '{s}:{s}'", .{ node.path, sub.name });
        for (sub.aliases) |alias| try w.print("|'{s}:{s}'", .{ node.path, alias });
        try w.print(") REPLY='{s}' ;;\n", .{sub.path});
    };
    try w.writeAll("        *) return 1 ;;\n    esac\n}\n");
}

fn offers(nodes: []const Node, w: *Writer, name: []const u8) Writer.Error!void {
    try writeAll(w, "_ensign_<id>_offer() {\n    case \"$1\" in\n", name);
    for (nodes) |node| {
        try w.print("        'options:{s}') REPLY='", .{node.path});
        var first = true;
        for (node.entries) |e| for (e.offered) |spelling| {
            if (!first) try w.writeByte(' ');
            try w.writeAll(spelling);
            first = false;
        };
        try w.writeAll("' ;;\n");
        if (node.subs.len == 0) continue;
        try w.print("        'commands:{s}') REPLY='", .{node.path});
        first = true;
        for (node.subs) |sub| if (!sub.hidden) {
            if (!first) try w.writeByte(' ');
            try w.writeAll(sub.name);
            first = false;
        };
        try w.writeAll("' ;;\n");
    }
    try w.writeAll("        *) REPLY= ;;\n    esac\n}\n");
}

fn pattern(w: *Writer, path: []const u8, spellings: []const []const u8) Writer.Error!void {
    try w.writeAll("        ");
    for (spellings, 0..) |spelling, n| try w.print("{s}'{s}:{s}'", .{ if (n == 0) "" else "|", path, spelling });
}

fn words(w: *Writer, prefix: []const u8, list: []const []const u8) Writer.Error!void {
    try w.writeAll(prefix);
    for (list, 0..) |item, n| try w.print("{s}{s}", .{ if (n == 0) "" else " ", item });
}

/// The case arms of a node's positionals: `#<index>`, and `#*` for a list
/// that takes the rest. With `values`, only enum positionals and their values.
fn positionals(w: *Writer, node: Node, values: bool) Writer.Error!void {
    for (node.positionals, 0..) |p, n| {
        if (values and p.kind != .values) continue;
        if (p.list) try w.print("        '{s}:#'*", .{node.path}) else try w.print("        '{s}:#{d}'", .{ node.path, n });
        if (values) {
            try words(w, ") REPLY='", p.values);
            try w.writeAll("' ;;\n");
        } else try w.print(") REPLY={s} ;;\n", .{tree.kindName(p.kind)});
    }
}
